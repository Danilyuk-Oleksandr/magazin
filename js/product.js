/* =========================
   CART STORAGE
========================= */

function getCart() {

    return JSON.parse(
        localStorage.getItem(
            "cybertechCart"
        )
    ) || [];

}

function saveCart(cart) {

    localStorage.setItem(
        "cybertechCart",
        JSON.stringify(cart)
    );

}

/* =========================
   UPDATE CART PREVIEW
========================= */

function updateCartPreview() {

    const cart = getCart();

    const totalItems =
        cart.reduce(
            (sum, item) =>
                sum + item.quantity,
            0
        );

    productCartCount.textContent =
        `${totalItems} items`;

}

